// Turns the listing originals in .media-src/ into web masters in public/media/images/
// and writes content/media.generated.ts (dimensions + blur placeholders).
// Responsive AVIF/WebP widths are produced on demand by next/image (sharp).
// Usage: npm run media
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { manifest } from "./media-manifest.mjs";

const SRC = path.resolve(".media-src");
const OUT = path.resolve("public/media/images");
const MAX = 2560;
fs.mkdirSync(OUT, { recursive: true });

const entries = [];
for (const m of manifest) {
  const input = path.join(SRC, `${m.from ?? m.slug}.jpg`);
  if (!fs.existsSync(input)) throw new Error(`Missing ${input}. Run npm run media:fetch first.`);

  let img = sharp(input).rotate();
  const meta = await sharp(await img.toBuffer()).metadata();
  if (m.crop) {
    const { left, top, width, height } = m.crop;
    img = sharp(await img.toBuffer()).extract({
      left: Math.round(left * meta.width),
      top: Math.round(top * meta.height),
      width: Math.round(width * meta.width),
      height: Math.round(height * meta.height),
    });
  }
  const master = await img
    .resize({ width: MAX, height: MAX, fit: "inside", withoutEnlargement: true })
    .modulate({ saturation: 0.96 })
    .jpeg({ quality: 80, mozjpeg: true, progressive: true })
    .toBuffer({ resolveWithObject: true });

  const file = path.join(OUT, `${m.slug}.jpg`);
  fs.writeFileSync(file, master.data);

  const blur = await sharp(master.data).resize(16).webp({ quality: 40 }).toBuffer();
  entries.push({
    slug: m.slug,
    src: `/media/images/${m.slug}.jpg`,
    width: master.info.width,
    height: master.info.height,
    blurDataURL: `data:image/webp;base64,${blur.toString("base64")}`,
  });
  console.log(m.slug.padEnd(18), `${master.info.width}x${master.info.height}`, `${(master.data.length / 1024).toFixed(0)} KB master`);
}

const body = entries
  .map((e) => `  "${e.slug}": { src: "${e.src}", width: ${e.width}, height: ${e.height}, blurDataURL: "${e.blurDataURL}" },`)
  .join("\n");
fs.writeFileSync(
  path.resolve("content/media.generated.ts"),
  `// Generated by scripts/process-images.mjs. Do not edit by hand.\n\nexport const media = {\n${body}\n} as const;\n\nexport type MediaSlug = keyof typeof media;\n`,
);
console.log(`\nWrote ${entries.length} images and content/media.generated.ts`);
