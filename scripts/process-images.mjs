// Turns the owner's photographs and film frames (media-source/) into web masters in
// public/media/images/ and writes content/media.generated.ts (dimensions, blur
// placeholders, credits). Responsive AVIF/WebP sizes are made on demand by next/image.
// Usage: FFMPEG=/path/to/ffmpeg npm run media
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { manifest } from "./media-manifest.mjs";

const FF = process.env.FFMPEG ?? "ffmpeg";
const OUT = path.resolve("public/media/images");
const VIDEOS = path.resolve("media-source/videos");
const MAX = 2400;
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

function frame(id, t) {
  const f = fs.readdirSync(VIDEOS).find((n) => n.includes(`[${id}]`));
  if (!f) throw new Error(`missing video ${id}`);
  return execFileSync(FF, ["-hide_banner", "-loglevel", "error", "-ss", String(t), "-i", path.join(VIDEOS, f), "-frames:v", "1", "-f", "image2pipe", "-vcodec", "png", "-"], {
    maxBuffer: 64 * 1024 * 1024,
  });
}

const entries = [];
for (const m of manifest) {
  const input = m.video ? frame(m.video, m.t) : fs.readFileSync(path.resolve(m.file));
  const rotated = await sharp(input).rotate().toBuffer();
  const meta = await sharp(rotated).metadata();
  let img = sharp(rotated);
  if (m.crop) {
    const { left, top, width, height } = m.crop;
    const L = Math.round(left * meta.width);
    const T = Math.round(top * meta.height);
    img = img.extract({ left: L, top: T, width: Math.min(meta.width - L, Math.round(width * meta.width)), height: Math.min(meta.height - T, Math.round(height * meta.height)) });
  }
  const master = await img
    .resize({ width: MAX, height: MAX, fit: "inside", withoutEnlargement: true })
    .sharpen(m.video ? { sigma: 0.6 } : undefined)
    .jpeg({ quality: 84, mozjpeg: true, progressive: true })
    .toBuffer({ resolveWithObject: true });
  fs.writeFileSync(path.join(OUT, `${m.slug}.jpg`), master.data);
  const blur = await sharp(master.data).resize(16).webp({ quality: 40 }).toBuffer();
  entries.push({ slug: m.slug, w: master.info.width, h: master.info.height, blur: `data:image/webp;base64,${blur.toString("base64")}`, credit: m.credit });
  console.log(m.slug.padEnd(20), `${master.info.width}x${master.info.height}`);
}

const body = entries
  .map((e) => `  "${e.slug}": { src: "/media/images/${e.slug}.jpg", width: ${e.w}, height: ${e.h}, blurDataURL: "${e.blur}"${e.credit ? `, credit: "${e.credit}"` : ""} },`)
  .join("\n");
fs.writeFileSync(
  path.resolve("content/media.generated.ts"),
  `// Generated by scripts/process-images.mjs. Do not edit by hand.\n\nexport interface MediaEntry {\n  src: string;\n  width: number;\n  height: number;\n  blurDataURL: string;\n  credit?: string;\n}\n\nexport const media = {\n${body}\n} satisfies Record<string, MediaEntry>;\n\nexport type MediaSlug = keyof typeof media;\n`,
);
console.log(`\n${entries.length} images`);
